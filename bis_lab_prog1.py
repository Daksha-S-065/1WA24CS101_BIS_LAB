import numpy as np
import random
from sklearn.datasets import load_iris
from sklearn.model_selection import cross_val_score
from sklearn.ensemble import RandomForestClassifier

# 1. Load Data
data = load_iris()
X, y = data.data, data.target

# 2. Define Hyperparameter Space Boundaries
PARAM_BOUNDS = {
    'n_estimators': (10, 200),
    'max_depth': (2, 20),
    'min_samples_split': (2, 10)
}

# =====================================================================
# DEFINE fitness(x):
# =====================================================================
def fitness(individual):
    n_estimators = int(individual[0])
    max_depth = int(individual[1])
    min_samples_split = int(individual[2])

    # Initialize the model with current hyperparameters
    clf = RandomForestClassifier(
        n_estimators=n_estimators,
        max_depth=max_depth,
        min_samples_split=min_samples_split,
        n_jobs=-1, # Keeps processing fast
        random_state=42
    )

    # Return average cross-validation score as fitness score
    scores = cross_val_score(clf, X, y, cv=3, n_jobs=-1)
    return float(np.mean(scores))

# =====================================================================
# INTERACTIVE USER INPUTS
# =====================================================================
print("--- Genetic Algorithm Hyperparameter Tuning Configuration ---")
try:
    population_size = int(input("Enter population size (Recommended: 10): "))
    mutation_rate = float(input("Enter mutation rate between 0 and 1 (Recommended: 0.1): "))
    crossover_rate = float(input("Enter crossover rate between 0 and 1 (Recommended: 0.8): "))
    generations = int(input("Enter number of generations (Recommended: 5): "))
    print("-" * 60)
except ValueError:
    print("\n❌ Invalid input type detected! Falling back to standard defaults.")
    population_size = 10
    mutation_rate = 0.1
    crossover_rate = 0.8
    generations = 5

# =====================================================================
# CREATE population with random values
# =====================================================================
population = []
for _ in range(population_size):
    ind = [
        random.randint(*PARAM_BOUNDS['n_estimators']),
        random.randint(*PARAM_BOUNDS['max_depth']),
        random.randint(*PARAM_BOUNDS['min_samples_split'])
    ]
    population.append(ind)

best_solution = None
best_fitness = -1.0

# =====================================================================
# FOR generation = 1 TO generations:
# =====================================================================
for generation in range(1, generations + 1):

    # CALCULATE fitness of every individual
    fitness_scores = [fitness(ind) for ind in population]

    # TRACK global best solution
    for i in range(population_size):
        if fitness_scores[i] > best_fitness:
            best_fitness = fitness_scores[i]
            best_solution = population[i].copy()

    # SELECT individuals with higher fitness as parents
    total_fit = sum(fitness_scores)
    probs = [f / total_fit for f in fitness_scores]

    # CREATE empty new_population
    new_population = []

    # WHILE size of new_population < population_size:
    while len(new_population) < population_size:

        # SELECT parent1 and parent2
        parent1, parent2 = random.choices(population, weights=probs, k=2)

        # IF random number < crossover_rate:
        if random.random() < crossover_rate:
            # CREATE child using crossover
            cross_point = random.randint(1, 2)
            child = parent1[:cross_point] + parent2[cross_point:]
        else:
            child = parent1.copy()

        # IF random number < mutation_rate:
        if random.random() < mutation_rate:
            # MUTATE child
            mutate_gene = random.randint(0, 2)
            if mutate_gene == 0:
                child[0] = random.randint(*PARAM_BOUNDS['n_estimators'])
            elif mutate_gene == 1:
                child[1] = random.randint(*PARAM_BOUNDS['max_depth'])
            else:
                child[2] = random.randint(*PARAM_BOUNDS['min_samples_split'])

        # ADD child to new_population
        new_population.append(child)

    # SET population = new_population
    population = new_population

    print(f"Gen {generation:02d}/{generations:02d} Completed. Best Fitness Found So Far: {best_fitness:.4f}")

# =====================================================================
# PRINT best_solution & PRINT fitness(best_solution)
# =====================================================================
print("\n" + "="*50)
print(f"PRINT best_solution: n_estimators={best_solution[0]}, max_depth={best_solution[1]}, min_samples_split={best_solution[2]}")
print(f"PRINT fitness(best_solution): {best_fitness:.4f}")
print("="*50)