import numpy as np
from sklearn.datasets import load_breast_cancer
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import cross_val_score

# 1. Define objective function f(x)
def objective_function(hyperparameters):
    """
    Evaluates the performance of a Random Forest Classifier given hyperparameters.
    PSO works on continuous spaces, so we round discrete parameters like n_estimators.
    """
    # Unpack hyperparameters from the particle position vector
    n_estimators = int(np.clip(hyperparameters[0], 10, 200))
    max_depth = int(np.clip(hyperparameters[1], 1, 20))
    min_samples_split = int(np.clip(hyperparameters[2], 2, 10))

    # Initialize the machine learning model
    model = RandomForestClassifier(
        n_estimators=n_estimators,
        max_depth=max_depth,
        min_samples_split=min_samples_split,
        random_state=42
    )

    # Load dataset (using Breast Cancer dataset as an example)
    X, y = load_breast_cancer(return_X_y=True)

    # Perform 3-fold cross-validation
    # We want to MAXIMIZE accuracy, so fitness = accuracy (higher is better)
    scores = cross_val_score(model, X, y, cv=3, scoring='accuracy', n_jobs=-1)

    return np.mean(scores)

# 2. Set N, MaxIter, w, c1 and c2
N = 15                 # Number of particles (swarm size)
MaxIter = 20           # Maximum iterations
w = 0.5                # Inertia weight
c1 = 1.5               # Cognitive coefficient (personal best influence)
c2 = 1.5               # Social coefficient (global best influence)

# Hyperparameter dimensions and bounds
# [n_estimators, max_depth, min_samples_split]
bounds_min = np.array([10, 1, 2])
bounds_max = np.array([200, 20, 10])
dimensions = len(bounds_min)

# 3. Initialize random position x[i] and velocity v[i]
x = np.random.uniform(bounds_min, bounds_max, (N, dimensions))
v = np.random.uniform(-1, 1, (N, dimensions))

# 4. Calculate fitness and set PBest and GBest
fitness = np.array([objective_function(particle) for particle in x])

PBest = np.copy(x)
PBest_fitness = np.copy(fitness)

g_best_index = np.argmax(fitness)  # For maximizing accuracy
GBest = np.copy(x[g_best_index])
GBest_fitness = fitness[g_best_index]

# Tracking history for visualization purposes
history = [GBest_fitness]

# 5. FOR iteration = 1 TO MaxIter DO
for iteration in range(MaxIter):

    # FOR each particle i = 1 TO N DO
    for i in range(N):

        # Generate r1 and r2
        r1 = np.random.uniform(0, 1, dimensions)
        r2 = np.random.uniform(0, 1, dimensions)

        # Update velocity
        v[i] = w * v[i] + c1 * r1 * (PBest[i] - x[i]) + c2 * r2 * (GBest - x[i])

        # Update position
        x[i] = x[i] + v[i]

        # Clip positions to ensure they stay within meaningful hyperparameter bounds
        x[i] = np.clip(x[i], bounds_min, bounds_max)

        # Calculate fitness
        current_fitness = objective_function(x[i])

        # Update PBest if current fitness is better (higher accuracy)
        if current_fitness > PBest_fitness[i]:
            PBest[i] = np.copy(x[i])
            PBest_fitness[i] = current_fitness

            # Update GBest if current fitness is better than the global best
            if current_fitness > GBest_fitness:
                GBest = np.copy(x[i])
                GBest_fitness = current_fitness

    history.append(GBest_fitness)
    print(f"Iteration {iteration+1}/{MaxIter} - Current Best Accuracy: {GBest_fitness:.5f}")

# 7. Display GBest and GBestFitness
print("\n=== Optimization Complete ===")
print(f"Best Accuracy (Fitness): {GBest_fitness:.5f}")
print(f"Optimal Hyperparameters found:")
print(f"  - n_estimators: {int(round(GBest[0]))}")
print(f"  - max_depth: {int(round(GBest[1]))}")
print(f"  - min_samples_split: {int(round(GBest[2]))}")